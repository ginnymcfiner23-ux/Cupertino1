# ---------------------------------------------------------------- helpers
def money(x, dp=0):
    if x in (None, ""):
        return "—"
    return "$" + format(round(float(x)), f",.{dp}f")

def pct(x, dp=2):
    return f"{x * 100:.{dp}f}%"

BADGE = {
    "verified": ('badge-ok', 'Verified &middot; official source'),
    "user": ('badge-user', 'User-provided &middot; unverified'),
    "assumption": ('badge-assume', 'Assumption &middot; model input'),
    "flagged": ('badge-flag', 'Unverified &middot; FLAGGED'),
    "model": ('badge-model', 'Model output'),
}

def badge(status):
    cls, label = BADGE[status]
    return f'<span class="badge {cls}">{label}</span>'

def src(*keys):
    out = []
    for k in keys:
        url = S.get(k, k if k.startswith("http") else "")
        if url:
            out.append(f'<a href="{url}" target="_blank" rel="noopener">source&nbsp;&rarr;</a>')
    return " ".join(out)

def table(headers, rows, caption=None, cls=""):
    """rows: list of dicts with cells=[...], source=[keys], status='verified'"""
    cap = f"<caption>{caption}</caption>" if caption else ""
    th = "".join(f"<th>{h}</th>" for h in headers)
    body = []
    for r in rows:
        tds = "".join(f"<td>{c}</td>" for c in r["cells"])
        links = src(*r.get("source", []))
        status = badge(r.get("status", "verified"))
        body.append(f"<tr>{tds}<td class='src'>{links}</td><td class='st'>{status}</td></tr>")
    return (f'<div class="tablewrap"><table class="{cls}">{cap}'
            f'<thead><tr>{th}<th>Source (official)</th><th>Status</th></tr></thead>'
            f'<tbody>{"".join(body)}</tbody></table></div>')

def h1(t, sub=""):
    s = f'<p class="sub">{sub}</p>' if sub else ""
    return f"<h1>{t}</h1>{s}"

def note(t):
    return f'<div class="note">{t}</div>'

